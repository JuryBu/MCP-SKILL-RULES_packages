        await store.mutateWorkspaceIndex(hash, index => { index.entries.push(realEntry); });
        assert.equal(projectCurrentAutoSummary(realEntry, hash).autoSummary, "");
        assert.match(JSON.stringify(await callbacks.get("memory_query")!({ workspace, query: realEntry.title, mode: "exact", depth: "summary" })), /旧摘要未用于检索/);
