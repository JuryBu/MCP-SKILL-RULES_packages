const entry = { id: base.id, title: base.title, tags: base.tags, category: base.category, searchSummary: base.searchSummary, autoSummary: base.autoSummary, autoSummaryProvenance: JSON.stringify(failedProvenance), createdAt: base.created, updatedAt: "2026-01-03", lastAccessed: base.updated, sizeBytes: Buffer.byteLength(failed), lineCount: store.countLines(failed) };
