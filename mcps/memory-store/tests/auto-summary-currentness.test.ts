    assert.match(queryOld, /未找到/);
    const queryBody = JSON.stringify(await callbacks.get("memory_query")!({ workspace, query: "changedbodyunique", mode: "exact", depth: "summary" }));
    assert.match(queryBody, /summary-fixture/);
    assert.match(queryBody, /最新生成失败/);
    assert.match(queryBody, /旧摘要未用于检索/);
    const batch = JSON.stringify(await callbacks.get("memory_batch")!({ operations: [{ action: "query", workspace, query: "obsoleteuniqueword", mode: "exact" }] }));
    assert.doesNotMatch(batch, /Currentness fixture/);
    const read = JSON.stringify(await callbacks.get("memory_read")!({ id: base.id, startLine: 1, endLine: 3 }));
    assert.match(read, /旧摘要未用于检索/);
    assert.equal(store.readMemoryFile(hash, base.id), failed);
    const largeHeader = store.buildMemoryFile({ ...base, autoSummaryProvenance: JSON.stringify({ ...failedProvenance, detail: "x".repeat(4000) }) }, "bodyafterlargeheader");
    store.writeMemoryFile(hash, base.id, largeHeader);
    assert.match(JSON.stringify(await callbacks.get("memory_query")!({ workspace, query: "bodyafterlargeheader", mode: "exact" })), /summary-fixture/);
    store.writeMemoryFile(hash, base.id, valid);
    entry.autoSummaryProvenance = JSON.stringify(generated) as typeof entry.autoSummaryProvenance;
    await store.mutateWorkspaceIndex(hash, index => { index.entries[0].autoSummaryProvenance = entry.autoSummaryProvenance; });
    assert.equal(projectCurrentAutoSummary(entry, hash).autoSummary, base.autoSummary);
    assert.equal(fuseSearch([entry], "obsoleteuniqueword", 10, hash).length, 1);
    assert.match(JSON.stringify(await callbacks.get("memory_query")!({ workspace, query: "obsoleteuniqueword", mode: "exact" })), /summary-fixture/);
    const legacyEntry = { ...entry, id: "legacy-retained", autoSummary: "legacyclueonly", autoSummaryProvenance: undefined };
    store.writeMemoryFile(hash, legacyEntry.id, store.buildMemoryFile({ ...base, id: legacyEntry.id }, "legacy body"));
    await store.mutateWorkspaceIndex(hash, index => { index.entries.push(legacyEntry); });
    assert.equal(inspectAutoSummaryCurrentness(oldContent).summary, "");
    assert.equal(projectCurrentAutoSummary(legacyEntry, hash).autoSummary, "legacyclueonly");
    assert.equal(fuseSearch([legacyEntry], "legacyclueonly", 10, hash).length, 1);
    for (const depth of ["index", "summary"]) {
        const legacyQuery = JSON.stringify(await callbacks.get("memory_query")!({ workspace, query: "legacyclueonly", mode: "exact", depth }));
        assert.match(legacyQuery, /legacy-retained/);
        assert.match(legacyQuery, /旧摘要仅作检索线索/);
    }
    const legacyBatch = JSON.stringify(await callbacks.get("memory_batch")!({ operations: [{ action: "query", workspace, query: "legacyclueonly", mode: "exact" }] }));
    assert.match(legacyBatch, /legacy-retained/);
    assert.match(legacyBatch, /旧摘要仅作检索线索/);
    assert.match(JSON.stringify(await callbacks.get("memory_read")!({ id: legacyEntry.id, startLine: 1, endLine: 3 })), /旧摘要仅作检索线索/);
